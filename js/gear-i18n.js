function gearItemName(item) {
    const lang = (typeof STATE !== 'undefined' && STATE && STATE.uiLang) || 'uk';
    if (lang === 'uk') return item.name;
    const tr = GEAR_NAME_I18N[item.id];
    return (tr && tr[lang]) || item.name;
}

